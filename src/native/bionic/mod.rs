use std::sync::Once;

pub fn register_libc_core() {
    static ONCE: Once = Once::new();
    ONCE.call_once(|| {
        memory::register();
        string::register();
        fortify::register();
        fatal::register();
        atexit::register();
        errno::register();
        printf_handlers::register();
        ctype::register();
        locale::register();
        mbstate::register();
        wide::register();
        strtonum::register();
        stdlib::register();
        prng::register();
        sort::register();
        env::register();
        sysinfo::register();
        props::register();
        time_handlers::register();
        tz_state::register();
        strftime::register();
        log::register();
        dl::register();
        fenv::register();
        math::register();
        libstdcxx::register();
        langinfo::register();
        libgen::register();
        stdio_files::register();
        wide_float::register();
        register_thread_group();
    });
}

fn register_thread_group() {
    pthread_attr::register();
    pthread_mutex::register();
    pthread_cond::register();
    pthread_rwlock::register();
    pthread_once::register();
    pthread_barrier::register();
    pthread_spin::register();
    semaphore::register();
    pthread_key::register();
    pthread_thread::register();
    atfork::register();
    syscall::register();
    tls_handlers::register();
    signal_handlers::register();
}
